// TEXT's lines over `modules` (Sunset's own, in menu order).
pub(super) fn apply(modules: &mut [Module]) {
    let ids: std::collections::HashMap<String, usize> = modules.iter().enumerate().map(|(i, m)| (norm(m.name), i)).collect();
    for line in TEXT.lines().skip(1) {
        let Some((k, v)) = line.split_once('=') else { continue };
        let Some(&i) = k.split_once('.').and_then(|(id, _)| ids.get(id)) else { continue };
        State::set_field(&mut modules[i..=i], k, v.trim());
    }
}
