#!/usr/bin/env python3
"""Render cargo-about's JSON into a plain-text THIRD-PARTY-LICENSES file and flag what needs a look.

    third_party.py OUT TITLE ABOUT_JSON [--own DIR]... [--text TITLE FILE]... [--html TITLE FILE]... [--flags FILE]

--own DIR    path crates under DIR are the work itself (Horizon's or Sunset's own crates), listed but not as third party;
             DIR/third_party/ stays third party
--text/--html  extra sections appended verbatim (fonts, the Rust standard library's notices); HTML is reduced to text
--flags FILE   also write the flags there (they always go to stderr)

Called by third-party.sh; edit the inputs, not the output.
"""
import html.parser
import json
import os
import re
import sys

PERMISSIVE = {
    "MIT", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "0BSD",
    "MIT-0", "Unicode-3.0", "Unicode-DFS-2016", "BSL-1.0", "CC0-1.0", "Unlicense", "bzip2-1.0.6", "NCSA",
    "CDLA-Permissive-2.0",
}
NOTICE = re.compile(r"^(NOTICE|NOTICES|THIRD[-_]PARTY[-_]NOTICES?)(\.(md|txt))?$", re.I)
RULE = "=" * 100


class Text(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.out, self.skip = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in ("style", "script"):
            self.skip += 1
        elif tag in ("p", "div", "br", "h1", "h2", "h3", "h4", "li", "tr", "pre", "hr"):
            self.out.append("\n")

    def handle_endtag(self, tag):
        if tag in ("style", "script"):
            self.skip -= 1
        elif tag in ("p", "div", "h1", "h2", "h3", "h4", "pre", "li"):
            self.out.append("\n")

    def handle_data(self, data):
        if not self.skip:
            self.out.append(data)


def html_text(path):
    p = Text()
    p.feed(open(path, encoding="utf-8").read())
    return re.sub(r"\n{3,}", "\n\n", "".join(p.out)).strip() + "\n"


def main():
    a = sys.argv[1:]
    out, title, src = a[0], a[1], a[2]
    own, extra, flags_file, i = [], [], None, 3
    while i < len(a):
        if a[i] == "--own":
            own.append(os.path.realpath(a[i + 1]) + os.sep); i += 2
        elif a[i] in ("--text", "--html"):
            extra.append((a[i], a[i + 1], a[i + 2])); i += 3
        elif a[i] == "--flags":
            flags_file = a[i + 1]; i += 2
        else:
            sys.exit(f"third_party.py: unknown argument {a[i]}")
    d = json.load(open(src, encoding="utf-8"))

    def is_own(pkg):
        mp = os.path.realpath(pkg["manifest_path"])
        return any(mp.startswith(o) and not mp.startswith(o + "third_party" + os.sep) for o in own)

    chosen = {}  # crate id -> licence ids cargo-about picked (several for AND)
    for lic in d["licenses"]:
        for u in lic["used_by"]:
            chosen.setdefault(u["crate"]["id"], set()).add(lic["id"])
    crates = sorted(d["crates"], key=lambda c: (c["package"]["name"], c["package"]["version"]))
    ours = [c for c in crates if is_own(c["package"])]
    third = [c for c in crates if not is_own(c["package"])]
    third_ids = {c["package"]["id"] for c in third}

    flags, notices = [], []
    for c in third:
        p = c["package"]
        picked = chosen.get(p["id"], set())
        name = f"{p['name']} {p['version']}"
        if not picked:
            flags.append(f"NO LICENCE FOUND: {name} (declared {c['license'] or 'nothing'})")
        for l in sorted(picked - PERMISSIVE):
            if l.startswith("MPL"):
                flags.append(f"MPL file-level: {name} (source location listed in the file)")
            else:
                flags.append(f"NON-PERMISSIVE {l}: {name} (declared {c['license']})")
        root = os.path.dirname(p["manifest_path"])
        for f in sorted(os.listdir(root)) if os.path.isdir(root) else []:
            if NOTICE.match(f) and os.path.isfile(os.path.join(root, f)):
                notices.append((name, f, open(os.path.join(root, f), encoding="utf-8", errors="replace").read()))
                flags.append(f"NOTICE carried: {name} {f}")

    w = []
    w.append(f"THIRD-PARTY LICENCES: {title}\n")
    w.append("Generated by client/release/third-party.sh (cargo-about 0.9.3) from the build's Cargo.lock; not edited by hand.\n")
    w.append("Each component below keeps its own copyright and licence. For a crate offered under a choice of licences,\n"
             "the licence used is the one given in its line.\n")
    if ours:
        w.append(f"\nThe work's own crates (not third party; see its licence files): " +
                 ", ".join(sorted({c['package']['name'] for c in ours})) + "\n")
    w.append(f"\n{RULE}\nRust crates ({len(third)})\n{RULE}\n")
    for c in third:
        p = c["package"]
        picked = " AND ".join(sorted(chosen.get(p["id"], {"(none found)"})))
        decl = "" if c["license"] in (picked, "") else f" (offered: {c['license']})"
        w.append(f"{p['name']} {p['version']}: {picked}{decl}" + (f"  {p['repository']}" if p.get("repository") else "") + "\n")
    w.append(f"\n{RULE}\nLicence texts\n{RULE}\n")
    for lic in d["licenses"]:
        users = sorted({f"{u['crate']['name']} {u['crate']['version']}" for u in lic["used_by"] if u["crate"]["id"] in third_ids})
        if not users:
            continue
        w.append(f"\n---- {lic['name']} ({lic['id']}), used by: {', '.join(users)}\n")
        if lic["id"].startswith("MPL"):
            w.append("Source code of these MPL-2.0 crates, unmodified: " +
                     ", ".join(f"https://crates.io/crates/{u.split(' ')[0]}/{u.split(' ')[1]}" for u in users) + "\n")
        w.append("\n" + lic["text"].strip() + "\n")
    if notices:
        w.append(f"\n{RULE}\nNOTICE files of the crates above\n{RULE}\n")
        for name, f, text in notices:
            w.append(f"\n---- {name}: {f}\n\n{text.strip()}\n")
    for kind, t, path in extra:
        w.append(f"\n{RULE}\n{t}\n{RULE}\n\n")
        w.append(html_text(path) if kind == "--html" else open(path, encoding="utf-8").read().strip() + "\n")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(w))
    summary = f"{title}: {len(third)} third-party crates, {len(notices)} NOTICE files, {len(extra)} extra sections"
    print(summary, file=sys.stderr)
    for fl in flags:
        print("  " + fl, file=sys.stderr)
    if flags_file:
        with open(flags_file, "w", encoding="utf-8", newline="\n") as f:
            f.write(summary + "\n" + "".join(f"  {fl}\n" for fl in flags))


main()
